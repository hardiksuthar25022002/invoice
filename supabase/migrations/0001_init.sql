-- Ledger — invoice maker: Supabase schema
--
-- Replaces the FastAPI + SQLAlchemy backend. Run this once against a fresh
-- Supabase project (SQL Editor, or `supabase db push` with the CLI).
--
-- Tables: profiles, companies, invoices, invoice_items
-- Includes: auth.users -> profiles trigger, per-user invoice numbering,
-- row level security, and the dashboard_stats() RPC.

-- ---------------------------------------------------------------------------
-- profiles: the "billed from" side of every invoice, one row per auth user.
-- ---------------------------------------------------------------------------

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  full_name text not null default '',
  business_name text,
  job_title text,
  address text,
  phone text,
  tax_id text,
  pan_number text,
  sac_code text,
  bank_account_name text,
  bank_account_number text,
  bank_ifsc text,
  upi_id text,
  created_at timestamptz not null default now()
);

-- Create a profile row whenever someone signs up. full_name arrives via
-- supabase.auth.signUp({ options: { data: { full_name } } }).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', '')
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- companies: the clients invoices are billed to.
-- ---------------------------------------------------------------------------

create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  address text,
  phone text,
  email text,
  created_at timestamptz not null default now()
);

create index if not exists companies_user_id_idx on public.companies (user_id);

-- ---------------------------------------------------------------------------
-- invoices
-- ---------------------------------------------------------------------------

create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  invoice_number text not null,
  company_id bigint not null references public.companies (id) on delete cascade,
  issue_date date not null default current_date,
  due_date date,
  status text not null default 'draft'
    check (status in ('draft', 'sent', 'paid', 'overdue')),
  notes text,
  tax_rate double precision not null default 0,
  discount double precision not null default 0,
  created_at timestamptz not null default now(),
  constraint uq_invoice_user_number unique (user_id, invoice_number)
);

create index if not exists invoices_user_id_idx on public.invoices (user_id);
create index if not exists invoices_company_id_idx on public.invoices (company_id);

-- Per-user sequential numbering (INV-0001), resilient to deleted invoices.
-- Ported from next_invoice_number() in the old FastAPI backend. The advisory
-- lock keeps concurrent inserts from handing out the same number.
create or replace function public.set_invoice_number()
returns trigger
language plpgsql
as $$
declare
  next_num int;
begin
  if new.invoice_number is null or new.invoice_number = '' then
    perform pg_advisory_xact_lock(hashtext(new.user_id::text));

    select coalesce(
             max(nullif(regexp_replace(invoice_number, '\D', '', 'g'), '')::int),
             0
           ) + 1
      into next_num
      from public.invoices
     where user_id = new.user_id;

    new.invoice_number := 'INV-' || lpad(next_num::text, 4, '0');
  end if;

  return new;
end;
$$;

drop trigger if exists invoices_set_number on public.invoices;

create trigger invoices_set_number
before insert on public.invoices
for each row execute function public.set_invoice_number();

-- ---------------------------------------------------------------------------
-- invoice_items
-- ---------------------------------------------------------------------------

create table if not exists public.invoice_items (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.invoices (id) on delete cascade,
  description text not null,
  quantity double precision not null default 1,
  unit_price double precision not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists invoice_items_invoice_id_idx
  on public.invoice_items (invoice_id);

-- ---------------------------------------------------------------------------
-- Row level security: a user only ever sees their own rows.
-- ---------------------------------------------------------------------------

alter table public.profiles enable row level security;
alter table public.companies enable row level security;
alter table public.invoices enable row level security;
alter table public.invoice_items enable row level security;

drop policy if exists "profiles select own" on public.profiles;
create policy "profiles select own" on public.profiles
  for select using (id = auth.uid());

drop policy if exists "profiles insert own" on public.profiles;
create policy "profiles insert own" on public.profiles
  for insert with check (id = auth.uid());

drop policy if exists "profiles update own" on public.profiles;
create policy "profiles update own" on public.profiles
  for update using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "companies access own" on public.companies;
create policy "companies access own" on public.companies
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "invoices access own" on public.invoices;
create policy "invoices access own" on public.invoices
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "invoice_items access own" on public.invoice_items;
create policy "invoice_items access own" on public.invoice_items
  for all
  using (
    exists (
      select 1 from public.invoices i
       where i.id = invoice_id and i.user_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1 from public.invoices i
       where i.id = invoice_id and i.user_id = auth.uid()
    )
  );

-- ---------------------------------------------------------------------------
-- dashboard_stats(): everything the Dashboard page needs, in one call.
-- Mirrors dashboard() from the old FastAPI backend:
--   total = round(subtotal * (1 + tax_rate / 100) - discount, 2)
--   overdue   = status 'overdue', or a past due date on a non-paid invoice
--   paid      = status 'paid'
--   outstanding = sent/draft that are not overdue
-- ---------------------------------------------------------------------------

create or replace function public.dashboard_stats()
returns jsonb
language plpgsql
stable
as $$
declare
  v_today date := current_date;
  v_result jsonb;
begin
  with calc as (
    select
      i.id,
      i.invoice_number,
      i.status,
      i.issue_date,
      i.due_date,
      i.company_id,
      i.notes,
      i.tax_rate,
      i.discount,
      round(
        (coalesce(it.subtotal, 0) * (1 + i.tax_rate / 100.0) - i.discount)::numeric,
        2
      ) as total,
      (
        i.status <> 'paid'
        and (
          i.status = 'overdue'
          or (i.due_date is not null and i.due_date < v_today)
        )
      ) as is_overdue
    from public.invoices i
    left join (
      select invoice_id, sum(quantity * unit_price) as subtotal
        from public.invoice_items
       group by invoice_id
    ) it on it.invoice_id = i.id
    where i.user_id = auth.uid()
  )
  select jsonb_build_object(
    'total_invoiced', coalesce(sum(total), 0),
    'total_paid', coalesce(sum(total) filter (where status = 'paid'), 0),
    'total_overdue', coalesce(sum(total) filter (where is_overdue), 0),
    'total_outstanding', coalesce(
      sum(total) filter (where status in ('sent', 'draft') and not is_overdue), 0
    ),
    'invoice_count', count(*),
    'company_count', (
      select count(*) from public.companies where user_id = auth.uid()
    ),
    'status_breakdown', coalesce(
      (
        select jsonb_object_agg(status, cnt)
          from (select status, count(*) as cnt from calc group by status) s
      ),
      '{}'::jsonb
    ),
    'monthly_totals', coalesce(
      (
        select jsonb_agg(
                 jsonb_build_object('month', month, 'total', total)
                 order by month
               )
          from (
            select to_char(issue_date, 'YYYY-MM') as month,
                   round(sum(total)::numeric, 2) as total
              from calc
             group by 1
          ) m
      ),
      '[]'::jsonb
    ),
    'recent_invoices', coalesce(
      (
        select jsonb_agg(entry order by ord desc)
          from (
            select
              c.id as ord,
              jsonb_build_object(
                'id', c.id,
                'invoice_number', c.invoice_number,
                'issue_date', c.issue_date,
                'due_date', c.due_date,
                'status', c.status,
                'notes', c.notes,
                'tax_rate', c.tax_rate,
                'discount', c.discount,
                'company', jsonb_build_object(
                  'id', comp.id,
                  'name', comp.name,
                  'address', comp.address,
                  'phone', comp.phone,
                  'email', comp.email
                ),
                'items', coalesce(
                  (
                    select jsonb_agg(
                             jsonb_build_object(
                               'id', ii.id,
                               'description', ii.description,
                               'quantity', ii.quantity,
                               'unit_price', ii.unit_price
                             )
                           )
                      from public.invoice_items ii
                     where ii.invoice_id = c.id
                  ),
                  '[]'::jsonb
                )
              ) as entry
              from calc c
              left join public.companies comp on comp.id = c.company_id
             order by c.id desc
             limit 5
          ) r
      ),
      '[]'::jsonb
    )
  )
  into v_result
  from calc;

  return v_result;
end;
$$;

grant execute on function public.dashboard_stats() to authenticated;
